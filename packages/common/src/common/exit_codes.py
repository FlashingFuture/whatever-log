"""프로세스 종료 코드 — 앱(recorder, hub, ...)이 공통으로 쓰는 것만 모은다.

supervisor가 "재시도해도 안 풀리는 종료"를 구분하려면 앱마다 같은 코드를 같은
뜻으로 써야 한다. 예전엔 앱마다 상수를 따로 정의하고 값이 같기를 관례로만 맞췄다.

특정 앱에서만 의미 있는 종료 코드는 여기 두지 않고 그 앱 디렉터리에서 정의한다
(이 값들과 겹치지 않게 4 이상을 쓴다). 여기에는 모든 앱에 같은 뜻인 것만 둔다.
"""

